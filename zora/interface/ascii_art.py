# Cada caractere braille codifica uma grade 2x4 de pontos (dots 1..8).
_DOT_BITS = (
    (0x01, 0x08),
    (0x02, 0x10),
    (0x04, 0x20),
    (0x40, 0x80),
)


def _braille_pixels(lines: list[str]) -> list[list[bool]]:
    height = len(lines) * 4
    width = max((len(line) for line in lines), default=0) * 2
    grid = [[False] * width for _ in range(height)]
    for row, line in enumerate(lines):
        for col, char in enumerate(line):
            code = ord(char)
            if 0x2800 <= code <= 0x28FF:
                mask = code - 0x2800
                for dr in range(4):
                    for dc in range(2):
                        if mask & _DOT_BITS[dr][dc]:
                            grid[row * 4 + dr][col * 2 + dc] = True
    return grid


def _trim(grid: list[list[bool]]) -> list[list[bool]]:
    if not grid or not grid[0]:
        return []
    rows = [i for i, row in enumerate(grid) if any(row)]
    if not rows:
        return []
    cols = [j for j in range(len(grid[0])) if any(grid[r][j] for r in rows)]
    if not cols:
        return []
    top, bottom = rows[0], rows[-1]
    left, right = cols[0], cols[-1]
    return [row[left : right + 1] for row in grid[top : bottom + 1]]


def _encode(grid: list[list[bool]]) -> list[str]:
    if not grid or not grid[0]:
        return []
    lines: list[str] = []
    for row in range(0, len(grid), 4):
        chars: list[str] = []
        for col in range(0, len(grid[0]), 2):
            mask = 0
            for dr in range(4):
                for dc in range(2):
                    r, c = row + dr, col + dc
                    if r < len(grid) and c < len(grid[0]) and grid[r][c]:
                        mask |= _DOT_BITS[dr][dc]
            chars.append(chr(0x2800 + mask))
        lines.append("".join(chars))
    return lines


def fit_braille(lines: list[str], max_cols: int = 78, max_rows: int = 30) -> list[str]:
    """Reduz uma arte braille para caber em ``max_cols`` x ``max_rows``."""
    grid = _trim(_braille_pixels(lines))
    if not grid:
        return []
    height, width = len(grid), len(grid[0])
    target_w = max(2, max_cols) * 2
    target_h = max(4, max_rows) * 4
    scale = min(target_w / width, target_h / height, 1.0)
    new_w = max(2, int(round(width * scale)) // 2 * 2)
    new_h = max(4, int(round(height * scale)) // 4 * 4)
    scaled = [[False] * new_w for _ in range(new_h)]
    for y in range(new_h):
        source_y = min(height - 1, int(y * height / new_h))
        for x in range(new_w):
            source_x = min(width - 1, int(x * width / new_w))
            scaled[y][x] = grid[source_y][source_x]
    result = _encode(scaled)
    return [line for line in result if line.strip("\u2800 ")]


